/**
 * Writes src/services/unicode/hidden.ts: the code points a recipient may never hold and a first line shows as a
 * visible marker (Shield R7-2). Built from Unicode 16.0.0 data, pinned by SHA-256 so the table only changes when
 * this script's pin does (as gen-confusables.ts). The set is the union of:
 *   General_Category Cc (controls), Cf (format), Zl, Zp (UnicodeData.txt);
 *   Default_Ignorable_Code_Point (DerivedCoreProperties.txt);
 *   Bidi_Control and Variation_Selector (PropList.txt);
 *   the tag block U+E0000..U+E007F.
 * Run from cli/:  npx tsx scripts/ildra/gen-hidden.ts [dir with the three .txt files]
 * Without a dir it downloads the pinned files from unicode.org.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const VERSION = '16.0.0'
const FILES = {
  'UnicodeData.txt': 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
  'DerivedCoreProperties.txt': '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
  'PropList.txt': '53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583',
} as const
type Name = keyof typeof FILES

const dir = process.argv[2]
const load = async (name: Name): Promise<string> => {
  const text = dir ? readFileSync(join(dir, name), 'utf8') : await (await fetch(`https://www.unicode.org/Public/${VERSION}/ucd/${name}`)).text()
  const got = createHash('sha256').update(text, 'utf8').digest('hex')
  if (got !== FILES[name]) throw new Error(`${name} sha256 ${got}, pinned ${FILES[name]}`)
  return text
}

const set = new Set<number>()
const addRange = (lo: number, hi: number): void => { for (let c = lo; c <= hi; c++) set.add(c) }

// UnicodeData.txt: code;name;gc;...  (ranges as <..., First> / <..., Last> pairs)
let first: number | null = null
for (const line of (await load('UnicodeData.txt')).split('\n')) {
  const f = line.split(';')
  if (f.length < 3) continue
  const cp = parseInt(f[0]!, 16)
  const gc = f[2]!
  const want = gc === 'Cc' || gc === 'Cf' || gc === 'Zl' || gc === 'Zp'
  if (f[1]!.endsWith(', First>')) { first = cp; continue }
  if (f[1]!.endsWith(', Last>')) { if (want) addRange(first!, cp); first = null; continue }
  if (want) set.add(cp)
}
// Property files: "XXXX..YYYY ; Prop # ..." or "XXXX ; Prop # ..."
const props = (text: string, prop: string): void => {
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)/.exec(line)
    if (m && m[3] === prop) addRange(parseInt(m[1]!, 16), parseInt(m[2] ?? m[1]!, 16))
  }
}
props(await load('DerivedCoreProperties.txt'), 'Default_Ignorable_Code_Point')
const propList = await load('PropList.txt')
props(propList, 'Bidi_Control')
props(propList, 'Variation_Selector')
addRange(0xE0000, 0xE007F)

const cps = [...set].sort((a, b) => a - b)
const ranges: [number, number][] = []
for (const c of cps) {
  const last = ranges.at(-1)
  if (last && c === last[1] + 1) last[1] = c
  else ranges.push([c, c])
}
const hex = (c: number): string => c.toString(16).toUpperCase().padStart(4, '0')
const data = ranges.map(([a, b]) => (a === b ? hex(a) : `${hex(a)}-${hex(b)}`)).join(';')
const out = `/**
 * GENERATED by scripts/ildra/gen-hidden.ts from Unicode ${VERSION} (UnicodeData.txt, DerivedCoreProperties.txt,
 * PropList.txt; sha256 pinned there). Do not edit. Shield R7-2: Cc, Cf, Zl, Zp, Default_Ignorable_Code_Point,
 * Bidi_Control, Variation_Selector and the tags U+E0000..U+E007F. ${cps.length} code points in ${ranges.length} ranges.
 * Unicode data: © Unicode, Inc., https://www.unicode.org/terms_of_use.html (Unicode License v3).
 */
export const HIDDEN_VERSION = '${VERSION}'
export const HIDDEN_SOURCES: Readonly<Record<string, string>> = ${JSON.stringify(FILES)}
export const HIDDEN_COUNT = ${cps.length}
/** "LO-HI;CP;..." in hex. */
export const HIDDEN_DATA =
  '${data}'
`
writeFileSync(join(import.meta.dirname, '..', '..', 'src', 'services', 'unicode', 'hidden.ts'), out)
console.log(`${cps.length} code points, ${ranges.length} ranges`)
