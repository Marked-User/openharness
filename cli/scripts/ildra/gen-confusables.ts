/**
 * Writes src/services/unicode/confusables.ts from Unicode's confusables.txt (UTS #39), pinned by version and
 * SHA-256 so the table only changes when this script's pin does. Run from cli/:
 *   npx tsx scripts/ildra/gen-confusables.ts [path/to/confusables.txt]
 * Without a path it downloads the pinned file from unicode.org. Shield R5 / v3.3: lookalike recipients.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const VERSION = '16.0.0'
const URL_ = `https://www.unicode.org/Public/security/${VERSION}/confusables.txt`
const SHA256 = '95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611'

const text = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(URL_)).text()
const got = createHash('sha256').update(text, 'utf8').digest('hex')
if (got !== SHA256) throw new Error(`confusables.txt sha256 ${got}, pinned ${SHA256}`)
const rows: string[] = []
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]{4,6})\s*;\s*([0-9A-F ]+?)\s*;\s*MA\b/.exec(line)
  if (!m) continue
  rows.push(`${m[1]}:${m[2]!.trim().split(/\s+/).join('.')}`)
}
const out = `/**
 * GENERATED by scripts/ildra/gen-confusables.ts from Unicode confusables.txt ${VERSION} (UTS #39),
 * sha256 ${SHA256}. Do not edit. ${rows.length} mappings (source code point to prototype).
 * Unicode data: © Unicode, Inc., https://www.unicode.org/terms_of_use.html (Unicode License v3).
 */
export const CONFUSABLES_VERSION = '${VERSION}'
export const CONFUSABLES_SHA256 = '${SHA256}'
export const CONFUSABLES_COUNT = ${rows.length}
/** "SRC:P1.P2;..." in hex. */
export const CONFUSABLES_DATA =
  '${rows.join(';')}'
`
writeFileSync(join(import.meta.dirname, '..', '..', 'src', 'services', 'unicode', 'confusables.ts'), out)
console.log(`${rows.length} mappings`)
